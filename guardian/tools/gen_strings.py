"""U1: writes app/src/main/res/values{,-zh,-de,-ja}/strings.xml from tools/strings_src.py.
Run after editing strings_src.py; tests/strings_check.py fails if the files are out of date."""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import strings_src as src  # noqa: E402

LANGS = [("values", 0), ("values-zh", 1), ("values-de", 2), ("values-ja", 3)]


def esc(s: str) -> str:
    raw = s
    s = s.replace("\\", "\\\\").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] in ("@", "?"):
        s = "\\" + s
    # aapt drops leading/trailing spaces unless the whole value is in double quotes.
    if raw != raw.strip():
        s = '"' + s + '"'
    return s


def render(idx: int, default: bool) -> str:
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- SPDX-License-Identifier: GPL-3.0-or-later -->",
           "<!-- Generated by tools/gen_strings.py from tools/strings_src.py. Do not edit by hand. -->"]
    if idx in (2, 3):
        out.append("<!-- AI draft, not yet reviewed by a native speaker. -->")
    out.append("<resources>")
    if default:
        for k, v in src.NOT_TRANSLATED.items():
            out.append(f'    <string name="{k}" translatable="false">{esc(v)}</string>')
    for k, vals in src.STRINGS.items():
        out.append(f'    <string name="{k}">{esc(vals[idx])}</string>')
    for k, vals in src.PLURALS.items():
        out.append(f'    <plurals name="{k}">')
        for q, v in vals[idx].items():
            out.append(f'        <item quantity="{q}">{esc(v)}</item>')
        out.append("    </plurals>")
    out.append("</resources>")
    return "\n".join(out) + "\n"


def outputs():
    res = ROOT / "app/src/main/res"
    return {res / d / "strings.xml": render(i, d == "values") for d, i in LANGS}


if __name__ == "__main__":
    for path, text in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print("wrote", path.relative_to(ROOT))
